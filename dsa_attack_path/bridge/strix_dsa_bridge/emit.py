"""Serialize bridge graphs to JSON (full contract) and topology TXT (C++ engine)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def emit_graph_json(graph: dict[str, Any], path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(graph, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return path


def emit_topology_txt(graph: dict[str, Any], path: Path) -> Path:
    """Write Phase-1 C++ topology format.

    Provenance cannot be expressed in the C++ TXT schema, so simulated vs finding
    is encoded into node names (``[SIM]`` / ``[FINDING]`` / ``[RUN]`` prefixes)
    and header comments. Prefer ``attack_graph.json`` for Phase 3+ consumers.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    lines: list[str] = [
        "# GENERATED BY strix_dsa_bridge — MODELED ATTACK GRAPH",
        "# NOT real pentest multi-hop proof. See companion attack_graph.json for provenance.",
        f"# disclaimer: {graph.get('disclaimer', '')}",
        f"# simulated_entry={graph.get('sources', {}).get('simulated_entry')}",
        f"# simulated_lateral={graph.get('sources', {}).get('simulated_lateral')}",
        "[NODES]",
        "# ID, Name, Type, Impact, Zone, isEntryPoint, isCrownJewel",
    ]
    for node in graph.get("nodes") or []:
        lines.append(
            ",".join(
                [
                    str(int(node["id"])),
                    str(node["name"]),
                    str(node["type"]),
                    str(int(node["impact"])),
                    str(node["zone"]),
                    "true" if node.get("is_entry_point") else "false",
                    "true" if node.get("is_crown_jewel") else "false",
                ]
            )
        )
    lines.append("[EDGES]")
    lines.append("# from, to, protocol, relation, probability, status")
    for edge in graph.get("edges") or []:
        lines.append(
            ",".join(
                [
                    str(int(edge["from"])),
                    str(int(edge["to"])),
                    str(edge.get("protocol") or "TCP"),
                    str(edge.get("relation") or "Unclassified"),
                    f"{float(edge.get('probability', 0.4)):.4f}",
                    str(edge.get("status") or "Active"),
                ]
            )
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def load_findings_file(path: Path) -> list[dict[str, Any]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(data, list):
        return [item for item in data if isinstance(item, dict)]
    if isinstance(data, dict) and isinstance(data.get("vulnerabilities"), list):
        return [item for item in data["vulnerabilities"] if isinstance(item, dict)]
    raise ValueError(f"{path} must be a JSON list of findings or an object with 'vulnerabilities'")


def load_run_record(path: Path | None) -> dict[str, Any]:
    if path is None or not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain a JSON object")
    return data
